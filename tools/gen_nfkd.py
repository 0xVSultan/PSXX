#!/usr/bin/env python3
"""core/lang/nfkd_tab.h: the decompositions (NFKD) of the characters of the BIP39 and Monero word lists that are not Hangul syllables (those are done by formula in
core/lang/nfkd.c): the accented Latin letters of Spanish and French, the voiced and semi-voiced kana of Japanese.  A BIP39 mnemonic in another language than English
goes into the seed as the NFKD form of its sentence, and the lists in RAM are in the composed form (NFC), which is what the screen draws.

  py -3.13 tools/gen_nfkd.py
"""
import os, sys, unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import data_pack as D


def chars():
    out = set()
    for lang in D.LANGS:
        for name, loader in ((lang[2], D.W.load_bip), (lang[3], D.W.load_xmr)):
            if name:
                for w in loader(name):
                    out |= set(w)
    return out


def main():
    ent = []
    for c in sorted(chars()):
        cp = ord(c)
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.normalize("NFKD", c)
        if d != c:
            ent.append((cp, [ord(x) for x in d]))
    assert all(len(d) <= 3 for _, d in ent) and all(cp < 0x10000 for cp, _ in ent)
    seq, offs = [], []
    for cp, d in ent:
        offs.append(len(seq))
        seq.extend(d)
    offs.append(len(seq))
    p = os.path.join(HERE, "..", "core", "lang", "nfkd_tab.h")
    with open(p, "w", newline="\n") as f:
        f.write("#pragma once\n/* Generated by tools/gen_nfkd.py -- do not edit. NFKD of the characters of the word lists (not the Hangul syllables): %d characters. */\n" % len(ent))
        f.write("#define NFKD_N %d\n" % len(ent))
        f.write("static const unsigned short NFKD_CP[NFKD_N] = {\n" + "".join("    " + ", ".join("0x%04x" % cp for cp, _ in ent[i:i + 10]) + ",\n" for i in range(0, len(ent), 10)) + "};\n")
        f.write("static const unsigned char NFKD_OFF[NFKD_N + 1] = {\n" + "".join("    " + ", ".join(str(o) for o in offs[i:i + 20]) + ",\n" for i in range(0, len(offs), 20)) + "};\n")
        f.write("static const unsigned short NFKD_SEQ[%d] = {\n" % len(seq) + "".join("    " + ", ".join("0x%04x" % s for s in seq[i:i + 10]) + ",\n" for i in range(0, len(seq), 10)) + "};\n")
    print("wrote core/lang/nfkd_tab.h: %d characters, %d code points" % (len(ent), len(seq)))


if __name__ == "__main__":
    main()
