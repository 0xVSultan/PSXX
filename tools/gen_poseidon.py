"""core/ec/poseidon_consts.h: the MDS matrix of Poseidon over the Pallas base field (width 3, 8 full and 56 partial rounds, x^5), read from the reference
implementation of the Zcash foundation (build/refzcash, orchard/poseidon.py). The round constants are not in the image: core/ec/poseidon.c makes them with the
Grain LFSR of the reference; the check is the test of the permutation (tests/test_poseidon.c, tools/gen_poseidon_vectors.py) and `--check`, which makes the constants
in Python the same way and compares them with the reference's."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "build", "refzcash"))
from zcash_test_vectors.orchard import poseidon as P

def le(x): return ",".join("0x%02x" % b for b in x.s.to_bytes(32, "little"))
lines = ["#pragma once", "/* Generated by tools/gen_poseidon.py -- do not edit. 32 byte little-endian field elements; the round constants are made by poseidon.c. */",
         "static const unsigned char POS_MDS[3][3][32] = {"]
for row in P.MDS_MATRIX:
    lines.append("    {" + ",".join("{%s}" % le(c) for c in row) + "},")
lines.append("};")
open(os.path.join(HERE, "..", "core", "ec", "poseidon_consts.h"), "w").write("\n".join(lines) + "\n")
print("written")

if "--check" in sys.argv:            # the Grain LFSR in Python (the algorithm of poseidon.c) against the constants of the reference
    p = 0x40000000000000000000000000000000224698fc094cf91b992d30ed00000001
    bits = lambda v, n: [(v >> (n - 1 - i)) & 1 for i in range(n)]
    s = bits(1, 2) + bits(0, 4) + bits(255, 12) + bits(3, 12) + bits(8, 10) + bits(56, 10) + [1] * 30

    def step():
        global s
        nb = s[62] ^ s[51] ^ s[38] ^ s[23] ^ s[13] ^ s[0]
        s = s[1:] + [nb]
        return nb

    def bit():
        b = step()
        while not b:
            step(); b = step()
        return step()

    for _ in range(160): step()
    rc = []
    while len(rc) < 192:
        v = 0
        for _ in range(255): v = (v << 1) | bit()
        if v < p: rc.append(v)
    assert rc == [c.s for c in P.ROUND_CONSTANTS], "the Grain LFSR does not give the constants of the reference"
    print("the 192 round constants are the Grain LFSR's")
