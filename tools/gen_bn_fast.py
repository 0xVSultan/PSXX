#!/usr/bin/env python3
"""Generates core/ec/bn_comba.c (the functions, one copy for the whole program) and core/ec/bn_comba.h (the prototypes): 256 x 256 -> 512 bit multiplication and squaring on 8 x 32 bit limbs as unrolled product
scanning (Comba): each column of the product is summed in a three word accumulator held in registers, so the 64 partial
products cost one multiply, a few adds and no memory traffic each (the schoolbook loops of bn.h reload and store the running
row for every product). The squaring does 36 multiplications instead of 64. Constant time. Usage: python tools/gen_bn_fast.py"""
import os

out = []
w = out.append
w("/* Generated by tools/gen_bn_fast.py -- do not edit. Unrolled product scanning, see there. */")
w("#include \"ec/bn_comba.h\"")
w("")
w("/* (c2:c1:c0) += a * b */")
w("#define BN_MAC(a, b) do {                                                                          \\")
w("        uint64_t t_ = (uint64_t) (a) * (b);                                                         \\")
w("        uint32_t lo_ = (uint32_t) t_, hi_ = (uint32_t) (t_ >> 32);                                  \\")
w("        c0 += lo_; hi_ += (c0 < lo_);                                                              \\")
w("        c1 += hi_; c2 += (c1 < hi_);                                                               \\")
w("    } while (0)")
w("")
w("void bn_mul_wide_comba(uint32_t t[16], const uint32_t a[8], const uint32_t b[8])")
w("{")
w("    uint32_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3], a4 = a[4], a5 = a[5], a6 = a[6], a7 = a[7];")
w("    uint32_t b0 = b[0], b1 = b[1], b2 = b[2], b3 = b[3], b4 = b[4], b5 = b[5], b6 = b[6], b7 = b[7];")
w("    uint32_t c0 = 0, c1 = 0, c2 = 0;")
for k in range(15):
    for i in range(8):
        j = k - i
        if 0 <= j < 8:
            w("    BN_MAC(a%d, b%d);" % (i, j))
    if k < 14:
        w("    t[%d] = c0; c0 = c1; c1 = c2; c2 = 0;" % k)
    else:
        w("    t[14] = c0; t[15] = c1;")
w("}")
w("")
w("void bn_sqr_wide_comba(uint32_t t[16], const uint32_t a[8])")
w("{")
w("    uint32_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3], a4 = a[4], a5 = a[5], a6 = a[6], a7 = a[7];")
w("    uint32_t c0 = 0, c1 = 0, c2 = 0;")
for k in range(15):
    cross = [(i, k - i) for i in range(8) if i < k - i < 8]
    if cross:
        w("    {")
        w("        uint32_t t0 = c0, t1 = c1, t2 = c2;")
        w("        c0 = c1 = c2 = 0;")
        for i, j in cross:
            w("        BN_MAC(a%d, a%d);" % (i, j))
        w("        c2 = (c2 << 1) | (c1 >> 31); c1 = (c1 << 1) | (c0 >> 31); c0 <<= 1;      /* the cross products count twice */")
        w("        { uint64_t s = (uint64_t) c0 + t0; c0 = (uint32_t) s; s = (uint64_t) c1 + t1 + (s >> 32); c1 = (uint32_t) s; c2 += t2 + (uint32_t) (s >> 32); }")
        w("    }")
    if k % 2 == 0:
        w("    BN_MAC(a%d, a%d);" % (k // 2, k // 2))
    if k < 14:
        w("    t[%d] = c0; c0 = c1; c1 = c2; c2 = 0;" % k)
    else:
        w("    t[14] = c0; t[15] = c1;")
w("}")
w("#undef BN_MAC")
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "ec")
open(os.path.join(here, "bn_comba.c"), "w", newline="\n").write("\n".join(out) + "\n")
HEADER = """#pragma once
/* 256 x 256 -> 512 bit product and square on 8 little-endian 32 bit limbs (bn_comba.c, generated by tools/gen_bn_fast.py). One copy
 * serves every caller: the unrolled code is 2.5 KB for the product and 2 KB for the square, which matters on the card. */
#include <stdint.h>

void bn_mul_wide_comba(uint32_t t[16], const uint32_t a[8], const uint32_t b[8]);
void bn_sqr_wide_comba(uint32_t t[16], const uint32_t a[8]);
"""
open(os.path.join(here, "bn_comba.h"), "w", newline="\n").write(HEADER)
print("wrote core/ec/bn_comba.c and bn_comba.h")
