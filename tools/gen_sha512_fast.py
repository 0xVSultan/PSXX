#!/usr/bin/env python3
"""Generates core/hash/sha512_fast.c: the SHA-512 compression function on pairs of 32 bit words (the PSX CPU has no 64 bit
registers and no rotate instruction). Two variants share the constants (core/hash/sha2_k.h, made at run time):
  sha512_block_loop  80 rounds in a loop, the eight working variables shuffled every round
  sha512_block_x8    the loop body is eight rounds with the variables renamed instead of moved (10 passes)
Both first expand the whole message schedule (80 pairs, 640 bytes) into a work area: with SHA512_SCRATCH defined (the PSX
build) that is the scratchpad at 0x1F800000 (1 cycle per access, main RAM costs about 6), else a local array.
sha512_block_fast is the one the library uses (SHA512_X8 selects the unrolled variant); sha512_hmac64 is one PBKDF2 step on words.
Usage: python tools/gen_sha512_fast.py"""
import os



def ror(l, h, n):
    """expressions (lo, hi) of the 64 bit rotation right by n of the pair (l, h)"""
    if n == 32:
        return h, l
    if n > 32:
        l, h = h, l
        n -= 32
    return ("((%s >> %d) | (%s << %d))" % (l, n, h, 32 - n), "((%s >> %d) | (%s << %d))" % (h, n, l, 32 - n))


def shr(l, h, n):
    return ("((%s >> %d) | (%s << %d))" % (l, n, h, 32 - n), "(%s >> %d)" % (h, n))


def xor3(a, b, c):
    return ("(%s ^ %s ^ %s)" % (a[0], b[0], c[0]), "(%s ^ %s ^ %s)" % (a[1], b[1], c[1]))


def big_sigma(l, h, ns):
    return xor3(*[ror(l, h, n) for n in ns])


out = []
w = out.append


def add_to(dl, dh, sl, sh, ind):
    """d += s on pairs (d, s variable names or expressions of side effect free values)"""
    w("%sx = %s + %s; %s += %s + (x < %s); %s = x;" % (ind, dl, sl, dh, sh, dl, dl))


def round_code(names, i, ind):
    """one round i with the working variables under the names of the eight roles a..h"""
    A, B, C, D, E, F, G, H = names
    s1 = big_sigma(E + "l", E + "h", (14, 18, 41))
    s0 = big_sigma(A + "l", A + "h", (28, 34, 39))
    w("%s{" % ind)
    w("%s\tu32 x, t1l, t1h, t2l, t2h, ul, uh;" % ind)
    w("%s\tt1l = %sl + %s; t1h = %sh + %s + (t1l < %sl);" % (ind, H, s1[0], H, s1[1], H))
    w("%s\tul = (%sl & %sl) ^ (~%sl & %sl); uh = (%sh & %sh) ^ (~%sh & %sh);" % (ind, E, F, E, G, E, F, E, G))
    w("%s\tx = t1l + ul; t1h += uh + (x < t1l); t1l = x;" % ind)
    w("%s\tx = t1l + KL[%s]; t1h += KH[%s] + (x < t1l); t1l = x;" % (ind, i, i))
    w("%s\tx = t1l + W[2 * (%s)]; t1h += W[2 * (%s) + 1] + (x < t1l); t1l = x;" % (ind, i, i))
    w("%s\tt2l = %s; t2h = %s;" % (ind, s0[0], s0[1]))
    w("%s\tul = (%sl & %sl) ^ (%sl & %sl) ^ (%sl & %sl); uh = (%sh & %sh) ^ (%sh & %sh) ^ (%sh & %sh);" %
      (ind, A, B, A, C, B, C, A, B, A, C, B, C))
    w("%s\tx = t2l + ul; t2h += uh + (x < t2l); t2l = x;" % ind)
    w("%s\tx = %sl + t1l; %sh += t1h + (x < %sl); %sl = x;" % (ind, D, D, D, D))
    w("%s\t%sl = t1l + t2l; %sh = t1h + t2h + (%sl < t1l);" % (ind, H, H, H))
    w("%s}" % ind)


w("/* Generated by tools/gen_sha512_fast.py -- do not edit. SHA-512 compression on 32 bit word pairs, see there. */")
w('#include "hash/sha512.h"')
w("")
w("typedef uint32_t u32;")
w("typedef uint32_t __attribute__((may_alias)) u32a;       /* the state is read as words of the uint64_t array it lives in */")
w("")
w('#include "hash/sha2_k.h"                               /* K, made at run time: SHA2_TABLES() before the rounds */')
w("#define KL sha2_kl")
w("#define KH sha2_kh")
w("")
w("/* the first 16 words of the schedule from a block of bytes (big endian); W holds lo, hi per word */")
w("static inline void load_block(u32 *W, const uint8_t *p)")
w("{")
w("\tfor (int i = 0; i < 16; i++) {")
w("\t\tW[2 * i + 1] = ((u32) p[8 * i] << 24) | ((u32) p[8 * i + 1] << 16) | ((u32) p[8 * i + 2] << 8) | p[8 * i + 3];")
w("\t\tW[2 * i] = ((u32) p[8 * i + 4] << 24) | ((u32) p[8 * i + 5] << 16) | ((u32) p[8 * i + 6] << 8) | p[8 * i + 7];")
w("\t}")
w("}")
w("")
w("/* the words 16..79 from the first 16 */")
w("static inline void expand(u32 *W)")
w("{")
w("\tfor (int i = 16; i < 80; i++) {")
w("\t\tu32 *a = W + 2 * (i - 15), *b = W + 2 * (i - 2), x, sl, sh;")
s0 = xor3(ror("a[0]", "a[1]", 1), ror("a[0]", "a[1]", 8), shr("a[0]", "a[1]", 7))
s1 = xor3(ror("b[0]", "b[1]", 19), ror("b[0]", "b[1]", 61), shr("b[0]", "b[1]", 6))
w("\t\tu32 l = W[2 * (i - 16)], h = W[2 * (i - 16) + 1];")
w("\t\tsl = %s; sh = %s;" % s0)
w("\t\tx = l + sl; h += sh + (x < l); l = x;")
w("\t\tx = l + W[2 * (i - 7)]; h += W[2 * (i - 7) + 1] + (x < l); l = x;")
w("\t\tsl = %s; sh = %s;" % s1)
w("\t\tx = l + sl; h += sh + (x < l); l = x;")
w("\t\tW[2 * i] = l; W[2 * i + 1] = h;")
w("\t}")
w("}")
w("")
w("#ifdef SHA512_SCRATCH")
w("#define WORK_AREA ((u32 *) 0x1F800000u)")
w("#else")
w("#define WORK_AREA W_local")
w("#endif")
w("")
w("#define LOAD(v, k) v##l = hw[2 * (k)]; v##h = hw[2 * (k) + 1];")
w("#define STORE(v, k) { u32 x_ = hw[2 * (k)] + v##l; hw[2 * (k) + 1] += v##h + (x_ < v##l); hw[2 * (k)] = x_; }")
w("")
w("/* the 80 rounds on the state words hw with the schedule W, and the feed-forward addition */")
for variant in ("loop", "x8"):
    w("static void compress_%s(u32a *hw, const u32 *W)" % variant)
    w("{")
    w("\tu32 al, ah, bl, bh, cl, ch, dl, dh, el, eh, fl, fh, gl, gh, hl, hh;")
    w("\tSHA2_TABLES();")
    w("\tLOAD(a, 0) LOAD(b, 1) LOAD(c, 2) LOAD(d, 3) LOAD(e, 4) LOAD(f, 5) LOAD(g, 6) LOAD(h, 7)")
    if variant == "loop":
        w("\tfor (int i = 0; i < 80; i++) {")
        round_code(list("abcdefgh"), "i", "\t\t")
        w("\t\t{ u32 sl = hl, sh = hh;       /* the new a is the h of this round; everything else moves down one place */")
        w("\t\t\thl = gl; hh = gh; gl = fl; gh = fh; fl = el; fh = eh; el = dl; eh = dh; dl = cl; dh = ch; cl = bl; ch = bh; bl = al; bh = ah;")
        w("\t\t\tal = sl; ah = sh; }")
        w("\t}")
    else:
        w("\tfor (int i = 0; i < 80; i += 8) {")
        names = list("abcdefgh")
        for j in range(8):
            rolled = [names[(k - j) % 8] for k in range(8)]
            round_code(rolled, "i + %d" % j, "\t\t")
        w("\t}")
    w("\tSTORE(a, 0) STORE(b, 1) STORE(c, 2) STORE(d, 3) STORE(e, 4) STORE(f, 5) STORE(g, 6) STORE(h, 7)")
    w("}")
    w("")
    w("void sha512_block_%s(uint64_t h[8], const uint8_t *p)" % variant)
    w("{")
    w("#ifndef SHA512_SCRATCH")
    w("\tu32 W_local[160];")
    w("#endif")
    w("\tu32 *const W = WORK_AREA;")
    w("\tload_block(W, p);")
    w("\texpand(W);")
    w("\tcompress_%s((u32a *) h, W);                  /* little endian: the low word of a state word comes first */" % variant)
    w("}")
    w("")
w("#ifdef SHA512_X8")
w("#define compress_fast compress_x8")
w("void sha512_block_fast(uint64_t h[8], const uint8_t *p) { sha512_block_x8(h, p); }")
w("#else")
w("#define compress_fast compress_loop")
w("void sha512_block_fast(uint64_t h[8], const uint8_t *p) { sha512_block_loop(h, p); }")
w("#endif")
w("")
w("/* u = HMAC(key, u) for a 64 byte message u kept as words, from the HMAC midstates of the key (the state after the one block")
w(" * key ^ ipad, key ^ opad). The message is one block each time: 64 bytes, 0x80, zeros, the length (128 + 64) * 8 = 1536 bits.")
w(" * The output words of the inner hash are the message words of the outer one: no byte conversion at all. */")
w("void sha512_hmac64(const uint64_t istate[8], const uint64_t ostate[8], uint64_t u[8])")
w("{")
w("#ifndef SHA512_SCRATCH")
w("\tu32 W_local[160];")
w("#endif")
w("\tu32 *const W = WORK_AREA;")
w("\tuint64_t h[8];")
w("\tu32a *const hw = (u32a *) h, *const uw = (u32a *) u;")
w("\tfor (int k = 0; k < 16; k++) W[k] = uw[k];")
w("\tW[16] = 0; W[17] = 0x80000000u;")
w("\tfor (int k = 18; k < 30; k++) W[k] = 0;")
w("\tW[30] = 1536; W[31] = 0;")
w("\tfor (int k = 0; k < 16; k++) hw[k] = ((const u32a *) istate)[k];")
w("\texpand(W);")
w("\tcompress_fast(hw, W);")
w("\tfor (int k = 0; k < 16; k++) W[k] = hw[k];         /* the inner digest is the message of the outer hash */")
w("\tfor (int k = 0; k < 16; k++) hw[k] = ((const u32a *) ostate)[k];")
w("\texpand(W);")
w("\tcompress_fast(hw, W);")
w("\tfor (int k = 0; k < 16; k++) uw[k] = hw[k];")
w("}")
w("")
text = "\n".join(out) + "\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "hash", "sha512_fast.c"), "w", newline="\n").write(text)
print("wrote core/hash/sha512_fast.c (%d bytes)" % len(text))
