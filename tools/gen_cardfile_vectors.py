"""The memory card fixture of tests/test_cardfile.c (tests/cardfile_card.txt): one card with a file of three blocks that are not next to each other and not in order,
a file of one block and a file of two blocks, written by tools/mkcard.py (the reference writer). Only the frames that are not zero are listed.

  py -3.13 tools/gen_cardfile_vectors.py

The data of the files is a pattern of the offset (the test makes it again): pat(i) = (i * 37 + (i >> 7) * 11 + SALT) & 255.
Lines: "file <name> <block list> <data length> <salt>" for what the card has, then "f <frame> <128 bytes in hex>"."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mkcard as M


def pat(n, salt):
    return bytes((i * 37 + (i >> 7) * 11 + salt) & 255 for i in range(n))


d = M.blank_card()
files = [
    ("BESCES-00000PSXXPK01", [7, 3, 11], 20000, 5),            # three blocks, in a chain that is not ascending
    ("BESCES-00000PSXXRQ01", [1], 100, 9),                     # one block
    ("BESCES-00000PSXXPK02", [5, 14], 9000, 77),               # two blocks
]
lines = []
for name, blocks, n, salt in files:
    got = M.add_file(d, name, pat(n, salt), "test file", blocks)
    assert got == blocks
    lines.append("file %s %s %d %d" % (name, ",".join(map(str, blocks)), n, salt))
    data, chain = M.find_file(d, name)                         # the reference reader reads it back
    assert chain == blocks and data[:n] == pat(n, salt) and not any(data[n:]), name
for f in range(1024):
    fr = bytes(d[f * M.FRAME:(f + 1) * M.FRAME])
    if any(fr):
        lines.append("f %d %s" % (f, fr.hex()))
open(os.path.join(HERE, "..", "tests", "cardfile_card.txt"), "w").write("# generated by tools/gen_cardfile_vectors.py\n" + "\n".join(lines) + "\n")
print("%d lines written" % len(lines))
