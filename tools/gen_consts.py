#!/usr/bin/env python3
"""Regenerate core/ec/ec_consts.h and cross-check the constants with libsecp256k1 / libsodium.
Requires: coincurve, pynacl."""
import os, coincurve, nacl.bindings as nb

p = 2**256 - 2**32 - 977
n = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
Gx = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
Gy = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
assert (Gy * Gy - Gx**3 - 7) % p == 0
pk = coincurve.PublicKey.from_secret((1).to_bytes(32, "big")).format(compressed=False)
assert pk[1:33] == Gx.to_bytes(32, "big") and pk[33:] == Gy.to_bytes(32, "big")

q = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
d = (-121665 * pow(121666, -1, q)) % q
By = 4 * pow(5, -1, q) % q
def sqrt(a):
    r = pow(a, (q + 3) // 8, q)
    if (r * r - a) % q: r = r * pow(2, (q - 1) // 4, q) % q
    assert (r * r - a) % q == 0
    return r
Bx = sqrt((By * By - 1) * pow(d * By * By + 1, -1, q) % q)
if Bx & 1: Bx = q - Bx
enc = (By | ((Bx & 1) << 255)).to_bytes(32, "little")
assert nb.crypto_scalarmult_ed25519_base_noclamp((1).to_bytes(32, "little")) == enc

def limbs(v): return "{" + ",".join("0x%08xu" % ((v >> (32 * i)) & 0xffffffff) for i in range(8)) + "}"
names = [("SECP_P", p), ("SECP_N", n), ("SECP_GX", Gx), ("SECP_GY", Gy), ("ED_P", q), ("ED_L", L),
         ("ED_D", d), ("ED_D2", 2 * d % q), ("ED_BX", Bx), ("ED_BY", By)]
with open(os.path.join(os.path.dirname(__file__), "..", "core", "ec", "ec_consts.h"), "w") as f:
    f.write("#pragma once\n/* Generated by tools/gen_consts.py -- do not edit. 256-bit values, little-endian 32-bit limbs. */\n")
    for k, v in names: f.write("#define %-8s %s\n" % (k, limbs(v)))
print("ok")
