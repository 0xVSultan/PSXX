#!/usr/bin/env python3
"""The English word lists of the generator and the signer as arithmetic coded blobs (tools/wl_pack.py, decoder core/wordlist/wl.c):
  core/coin/bip39_words.h   BIP39 English (tools/wordlist_dl/english.txt, SHA-256 2f5eed53...),
  core/coin/xmr_words.h     Monero English (tools/wordlist_dl_xmr/english.h, from monero-project/monero src/mnemonics/english.h).
The words keep their order (the position is the index). The round trip is checked with the independent Python decoder of wl_pack.py.
Run:  py -3.13 tools/gen_words_ac.py"""
import hashlib, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import wl_pack as W

def header(path, comment, define, name, blob):
    lines = ["    " + ",".join("0x%02x" % b for b in blob[i:i + 16]) + "," for i in range(0, len(blob), 16)]
    with open(path, "w", newline="\n") as f:
        f.write("#pragma once\n/* Generated by tools/gen_words_ac.py -- do not edit. %s, arithmetic coded (tools/wl_pack.py, %d bytes). */\n" % (comment, len(blob)))
        f.write("%s\nstatic const unsigned char %s[%d] = {\n%s\n};\n" % (define, name, len(blob), "\n".join(lines)))

raw = open(os.path.join(here, "wordlist_dl", "english.txt"), "rb").read()
assert hashlib.sha256(raw).hexdigest() == "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
bip = raw.decode().split()
assert len(bip) == 2048 and bip == sorted(bip) and len(set(w[:4] for w in bip)) == 2048 and max(map(len, bip)) <= 8
blob, _, nsym, rows = W.pack(bip, "english"); W.unpack_check(blob, bip)
header(os.path.join(here, "..", "core", "coin", "bip39_words.h"), "BIP39 English wordlist (2048 words, source SHA-256 2f5eed53...)", "#define BIP39_NWORDS 2048", "BIP39_EN_AC", blob)
print("BIP39 English: %d bytes (nsym %d, rows %d)" % (len(blob), nsym, rows))

src = open(os.path.join(here, "wordlist_dl_xmr", "english.h"), encoding="utf-8").read()
body = src[src.index("words[NWORDS]"):]
body = body[body.index("{"):body.index("};")]
xmr = re.findall(r'"([a-z]+)"', body)
assert len(xmr) == 1626 and len(set(w[:3] for w in xmr)) == 1626 and len(set(xmr)) == 1626 and max(map(len, xmr)) <= 12
# the Monero list from the BIP39 one: the BIP39 words it keeps (a mask) and its own words (a blob), merged in alphabetical order (core/wordlist/wl.c wl_merge)
assert xmr == sorted(xmr)
mask = [w in set(xmr) for w in bip]
own = [w for w in xmr if w not in set(bip)]
assert W.merge(bip, mask, own) == xmr
blob, _, nsym, rows = W.pack(own, "english"); W.unpack_check(blob, own)
mcoded = W.pack_mask(mask)                                         # the mask with the coder of the lists (wl.c wl_mask_decode): 188 + 2 bytes instead of 256
assert W.Decoder(mcoded).bits(2048) == [int(m) for m in mask]
path = os.path.join(here, "..", "core", "coin", "xmr_words.h")
header(path, "Monero English wordlist (1626 words, source SHA-256 %s): the %d words that are not BIP39 words" % (hashlib.sha256(src.encode()).hexdigest(), len(own)),
       "#define XMR_NWORDS 1626\n#define XMR_EN_OWN %d" % len(own), "XMR_EN_AC", blob)
lines = ["    " + ",".join("0x%02x" % b for b in mcoded[i:i + 16]) + "," for i in range(0, len(mcoded), 16)]
with open(path, "a", newline="\n") as f:
    f.write("/* the %d BIP39 words the Monero list keeps: a mask of one bit per BIP39 word, coded (tools/wl_pack.py pack_mask) */\nstatic const unsigned char XMR_EN_MASK[%d] = {\n%s\n};\n"
            % (sum(mask), len(mcoded), "\n".join(lines)))
print("Monero English: %d own words in %d bytes (nsym %d, rows %d) and a mask of the %d BIP39 words (%d bytes coded)" % (len(own), len(blob), nsym, rows, sum(mask), len(mcoded)))
