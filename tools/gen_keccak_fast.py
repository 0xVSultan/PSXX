#!/usr/bin/env python3
"""Generates core/hash/keccak_fast.c: Keccak-f[1600] on pairs of 32 bit words (the PSX CPU has no 64 bit registers and no
rotate instruction, so every 64 bit rotation is written out as two shifts and an or per word). The state lives in 50 words
in place; theta and the rho / pi cycle are straight-line code with constant shifts, chi is a loop over the five rows. The whole
round is about 600 instructions (2.4 KB), so the loop body stays inside the 4 KB instruction cache of the PSX CPU: a fully
unrolled round (1400 instructions) does not, and ran no faster than compact table driven loops.
With KECCAK_SCRATCH defined (the PSX build) the state and the column sums live in the 1 KB scratchpad (0x1F800000): a load from
main RAM costs about 6 cycles on the PSX (no data cache), from the scratchpad one; the permutation is about 1.7 times faster.
Usage: python tools/gen_keccak_fast.py"""
import os, sys

RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808a, 0x8000000080008000, 0x000000000000808b, 0x0000000080000001,
      0x8000000080008081, 0x8000000000008009, 0x000000000000008a, 0x0000000000000088, 0x0000000080008009, 0x000000008000000a,
      0x000000008000808b, 0x800000000000008b, 0x8000000000008089, 0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
      0x000000000000800a, 0x800000008000000a, 0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
ROTC = [1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 2, 14, 27, 41, 56, 8, 25, 43, 62, 18, 39, 61, 20, 44]
PILN = [10, 7, 11, 17, 18, 3, 5, 16, 8, 21, 24, 4, 15, 23, 19, 13, 12, 2, 20, 14, 22, 9, 6, 1]


def rot(lo, hi, n):
    """expressions (lo', hi') of the 64 bit rotation left by n of the pair (lo, hi)"""
    n %= 64
    if n >= 32:
        lo, hi = hi, lo
        n -= 32
    if n == 0:
        return lo, hi
    return ("((%s << %d) | (%s >> %d))" % (lo, n, hi, 32 - n), "((%s << %d) | (%s >> %d))" % (hi, n, lo, 32 - n))


out = []
w = out.append
w("/* Generated by tools/gen_keccak_fast.py -- do not edit. Keccak-f[1600] on 32 bit word pairs, see there. */")
w('#include "hash/keccak.h"')
w("#include <string.h>")
w("")
w("typedef uint32_t u32;")
w("")
w("#ifndef KECCAK_ROUNDS")
w("#define KECCAK_ROUNDS 24                               /* fewer only for the vanity bench (hal/psx/vb_keccak23.c) */")
w("#endif")
w("")
w("static const u32 RCL[24] = {%s};" % ",".join("0x%08xu" % (c & 0xFFFFFFFF) for c in RC))
w("static const u32 RCH[24] = {%s};" % ",".join("0x%08xu" % (c >> 32) for c in RC))
w("")
w("void keccak_f1600(uint64_t st[25])")
w("{")
w("#ifdef KECCAK_SCRATCH")
w("\tu32 *const s = (u32 *) 0x1F800000u, *const cl = s + 50, *const ch = s + 55;   /* scratchpad: no wait states */")
w("#else")
w("\tu32 s[50], cl[5], ch[5];")
w("#endif")
w("\tu32 dl, dh, tl, th, bl, bh;")
w("\tmemcpy(s, st, 200);                               /* little endian lanes: low word first */")
w("\tfor (int r = 0; r < KECCAK_ROUNDS; r++) {")
w("\t\t/* theta */")
for x in range(5):
    w("\t\tcl[%d] = %s;" % (x, " ^ ".join("s[%d]" % (2 * (x + 5 * y)) for y in range(5))))
    w("\t\tch[%d] = %s;" % (x, " ^ ".join("s[%d]" % (2 * (x + 5 * y) + 1) for y in range(5))))
for x in range(5):
    l, h = rot("cl[%d]" % ((x + 1) % 5), "ch[%d]" % ((x + 1) % 5), 1)
    w("\t\tdl = cl[%d] ^ %s;" % ((x + 4) % 5, l))
    w("\t\tdh = ch[%d] ^ %s;" % ((x + 4) % 5, h))
    for y in range(5):
        i = x + 5 * y
        w("\t\ts[%d] ^= dl; s[%d] ^= dh;" % (2 * i, 2 * i + 1))
w("\t\t/* rho and pi: the 24 lanes move along one cycle */")
w("\t\ttl = s[2]; th = s[3];")
for k in range(24):
    j = PILN[k]
    l, h = rot("tl", "th", ROTC[k])
    w("\t\tbl = s[%d]; bh = s[%d]; s[%d] = %s; s[%d] = %s; tl = bl; th = bh;" % (2 * j, 2 * j + 1, 2 * j, l, 2 * j + 1, h))
w("\t\t/* chi, row by row */")
w("\t\tfor (int y = 0; y < 50; y += 10) {")
for x in range(5):
    w("\t\t\tu32 l%d = s[y + %d], h%d = s[y + %d];" % (x, 2 * x, x, 2 * x + 1))
for x in range(5):
    w("\t\t\ts[y + %d] = l%d ^ (~l%d & l%d); s[y + %d] = h%d ^ (~h%d & h%d);" % (2 * x, x, (x + 1) % 5, (x + 2) % 5, 2 * x + 1, x, (x + 1) % 5, (x + 2) % 5))
w("\t\t}")
w("\t\ts[0] ^= RCL[r]; s[1] ^= RCH[r];")
w("\t}")
w("\tmemcpy(st, s, 200);")
w("}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "hash", "keccak_fast.c"), "w", newline="\n").write("\n".join(out) + "\n")
print("wrote core/hash/keccak_fast.c")
